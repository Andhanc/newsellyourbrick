export function formatDialogPathForPrompt(dialogPath = DEFAULT_CONFIG.dialogPath) {
  if (!Array.isArray(dialogPath) || !dialogPath.length) return ''
  const lines = dialogPath.map((item, i) => {
    const n = item.step ?? i + 1
    return `${n}. **${item.title || `Шаг ${n}`}:** ${item.description || ''}`
  })
  return `\n\n**ПУТЬ ДИАЛОГА (один этап за раз):**\n${lines.join('\n')}\n`
}

