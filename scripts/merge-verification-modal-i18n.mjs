const TARGET_DIRS = [
  'src/i18n/locales/mainPage',
  'apps/client/src/legacy/i18n/locales/mainPage',
]

const root = path.resolve(import.meta.dirname, '..')

for (const dir of TARGET_DIRS) {
  for (const locale of LOCALES) {
    const filePath = path.join(root, dir, `${locale}.json`)
    const json = JSON.parse(fs.readFileSync(filePath, 'utf8'))
    Object.assign(json, KEYS[locale])
    fs.writeFileSync(filePath, `${JSON.stringify(json, null, 2)}\n`)
    console.log(`updated ${path.relative(root, filePath)} (+${Object.keys(KEYS[locale]).length} keys)`)
  }
}
