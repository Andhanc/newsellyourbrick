function sortKeys(obj) {
  return Object.fromEntries(Object.keys(obj).sort().map((k) => [k, obj[k]]))
}

function buildPack() {
  const enReuse = pickReuseKeys(enMain)
  const ruReuse = pickReuseKeys(ruMain)

  const en = sortKeys({ ...enReuse, ...EXTRA_EN })
  const ru = sortKeys({ ...ruReuse, ...EXTRA_RU })

  // Ensure every EN key has RU (fallback to EN)
  for (const key of Object.keys(en)) {
    if (ru[key] == null) {
      ru[key] = ruMain[key] ?? EXTRA_RU[key] ?? en[key]
    }
  }
  for (const key of Object.keys(ru)) {
    if (en[key] == null) en[key] = enMain[key] ?? EXTRA_EN[key] ?? ru[key]
  }

  return { en, ru }
}

const { en, ru } = buildPack()
const outPath = path.join(root, 'scripts/owner-cabinet-i18n-pack.mjs')

const header = `/**
 * Owner-test cabinet + add-property wizard i18n pack.
 * Generated by scripts/build-owner-cabinet-i18n-pack.mjs — edit extras there and rebuild.
 *
 * Reuses existing mainPage keys: addProperty*, ownerProfile*, ownerSettings*,
 * ownerSales*, ownerTestDrive*, ownerAnalytics*, etc.
 * New keys use ownerTest_* (cabinet) or oap_* (wizard) prefixes.
 */
`

const body = `${header}export const PACK = ${JSON.stringify({ ru, en }, null, 2)}\n`
fs.writeFileSync(outPath, body, 'utf8')

const total = Object.keys(en).length
console.log(`Wrote ${outPath}`)
console.log(`Total keys: ${total} (en), ${Object.keys(ru).length} (ru)`)
