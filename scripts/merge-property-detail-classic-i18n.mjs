function mergeLocaleFile(filePath, lang) {
  const pack = PACK[lang]
  if (!pack) return { added: 0, updated: 0 }
  const original = JSON.parse(fs.readFileSync(filePath, 'utf8'))
  const out = { ...original }
  let added = 0
  let updated = 0
  const forceLang = ['de', 'es', 'fr', 'sv'].includes(lang)
  for (const [key, value] of Object.entries(pack)) {
    if (!(key in out)) {
      out[key] = value
      added += 1
    } else if (forceLang && FORCE_OVERWRITE_IN_DE_ES_FR_SV.has(key)) {
      if (out[key] !== value) {
        out[key] = value
        updated += 1
      }
    }
  }
  fs.writeFileSync(filePath, `${JSON.stringify(out, null, 2)}\n`, 'utf8')
  return { added, updated }
}

for (const dir of LOCALE_DIRS) {
  if (!fs.existsSync(dir)) continue
  for (const lang of Object.keys(PACK)) {
    const filePath = path.join(dir, `${lang}.json`)
    if (!fs.existsSync(filePath)) {
      console.warn('skip missing', filePath)
      continue
    }
    const { added, updated } = mergeLocaleFile(filePath, lang)
    console.log(`${path.relative(ROOT, filePath)}: +${added} ~${updated}`)
  }
}
